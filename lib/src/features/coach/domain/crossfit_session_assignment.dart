import '../../training/domain/entities/crossfit.dart';
import 'coach_models.dart';

class CrossFitSessionAssignment {
  const CrossFitSessionAssignment({
    required this.title,
    required this.date,
    required this.blocks,
    required this.exercises,
    this.category = 'CrossFit',
    this.focus,
    this.coachNotes,
  });

  final String title;
  final DateTime date;
  final List<CrossFitBlockAssignment> blocks;
  final List<ExerciseAssignment> exercises;
  final String? category;
  final String? focus;
  final String? coachNotes;

  Map<String, dynamic> toJson() => {
    'title': title.trim(),
    'category': category,
    'focus': focus,
    'coach_notes': coachNotes,
    'scheduled_for':
        '${date.year.toString().padLeft(4, '0')}-${date.month.toString().padLeft(2, '0')}-${date.day.toString().padLeft(2, '0')}',
    'exercises': [
      for (var i = 0; i < exercises.length; i++)
        exercises[i].toJson(i + 1),
    ],
    'blocks': [
      for (var i = 0; i < blocks.length; i++)
        blocks[i].toJson(i + 1),
    ],
  };
}

class CrossFitBlockAssignment {
  const CrossFitBlockAssignment({
    required this.type,
    required this.title,
    this.coachNote,
    this.prescription = const {},
    this.wod,
  });

  final TrainingBlockType type;
  final String title;
  final String? coachNote;
  final Map<String, dynamic> prescription;
  final CrossFitWodAssignment? wod;

  Map<String, dynamic> toJson(int order) => {
    'order': order,
    'type': type.name,
    'title': title.trim(),
    'coach_note': coachNote,
    'prescription': prescription,
    if (wod != null) 'wod': wod!.toJson(),
  };
}

/// WOD ids are generated by FastAPI. Coach POSTs must not include them.
class CrossFitWodAssignment {
  const CrossFitWodAssignment({
    required this.format,
    required this.scoreType,
    this.durationSeconds,
    this.timeCapSeconds,
    this.rounds,
    this.scalingOptions = const [ScalingLevel.rx, ScalingLevel.scaled],
    this.scoreConfig = const {},
  });

  final WodFormat format;
  final WodScoreType scoreType;
  final int? durationSeconds;
  final int? timeCapSeconds;
  final int? rounds;
  final List<ScalingLevel> scalingOptions;
  final Map<String, dynamic> scoreConfig;

  Map<String, dynamic> toJson() => {
    'format': switch (format) {
      WodFormat.forTime => 'for_time',
      WodFormat.amrap => 'amrap',
      WodFormat.emom => 'emom',
      WodFormat.roundsForTime => 'rounds_for_time',
      WodFormat.chipper => 'chipper',
      WodFormat.intervals => 'intervals',
      WodFormat.maxLoad => 'max_load',
      WodFormat.maxReps => 'max_reps',
      WodFormat.calories => 'calories',
      WodFormat.distance => 'distance',
      WodFormat.tabata => 'tabata',
      WodFormat.custom => 'custom',
    },
    'score_type': switch (scoreType) {
      WodScoreType.time => 'time',
      WodScoreType.roundsReps => 'rounds_reps',
      WodScoreType.load => 'load',
      WodScoreType.reps => 'reps',
      WodScoreType.calories => 'calories',
      WodScoreType.distance => 'distance',
      WodScoreType.intervals => 'intervals',
      WodScoreType.none => 'none',
    },
    if (durationSeconds != null) 'duration_seconds': durationSeconds,
    if (timeCapSeconds != null) 'time_cap_seconds': timeCapSeconds,
    if (rounds != null) 'rounds': rounds,
    'scaling_options': scalingOptions.map((level) => level.name).toList(),
    'score_config': scoreConfig,
  };
}

WodScoreType defaultScoreType(WodFormat format) => switch (format) {
  WodFormat.forTime || WodFormat.roundsForTime || WodFormat.chipper =>
    WodScoreType.time,
  WodFormat.amrap => WodScoreType.roundsReps,
  WodFormat.emom || WodFormat.intervals || WodFormat.tabata =>
    WodScoreType.intervals,
  WodFormat.maxLoad => WodScoreType.load,
  WodFormat.maxReps => WodScoreType.reps,
  WodFormat.calories => WodScoreType.calories,
  WodFormat.distance => WodScoreType.distance,
  WodFormat.custom => WodScoreType.none,
};

String wodFormatLabel(WodFormat format) => switch (format) {
  WodFormat.forTime => 'For Time',
  WodFormat.amrap => 'AMRAP',
  WodFormat.emom => 'EMOM',
  WodFormat.roundsForTime => 'Rounds for Time',
  WodFormat.chipper => 'Chipper',
  WodFormat.intervals => 'Intervals',
  WodFormat.maxLoad => 'Max Load',
  WodFormat.maxReps => 'Max Reps',
  WodFormat.calories => 'Calories',
  WodFormat.distance => 'Distance',
  WodFormat.tabata => 'Tabata',
  WodFormat.custom => 'Custom (No Score)',
};
